/** Dev-only: the mirror asks to complete the look (a bottom for a top, then shoes on the mannequin), the picture, and the "To go with it" rows under it. App on :3100 with the mock env. */
import { chromium, devices } from "@playwright/test";
import { execSync } from "node:child_process";
const out = process.argv[2];
const env = { ...process.env, DATABASE_URL: "postgresql://postgres@localhost:5433/fenscloset_e2e", DEV_MODE: "true", SEED_FORCE: "true", MOCK_S3: "true" };
execSync(`psql -h localhost -p 5433 -U postgres -d fenscloset_e2e -c 'DROP SCHEMA public CASCADE; CREATE SCHEMA public;'`, { stdio: "ignore" });
execSync("npx prisma migrate deploy && npx tsx prisma/seed.ts && npx tsx e2e/set-password.ts jeff@everbowl.com closet-rocks-2026 && npx tsx e2e/seed-closets.ts Jeff", { stdio: "ignore", env });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
const ctx = await browser.newContext({ ...devices["iPhone 15"] });
const page = await ctx.newPage();
const base = "http://localhost:3100";
const shot = async (name) => { await page.waitForTimeout(500); await page.screenshot({ path: `${out}/${name}.png` }); };
await page.goto(base + "/login");
await page.getByLabel("Email").fill("jeff@everbowl.com"); await page.getByLabel("Password").fill("closet-rocks-2026");
await page.getByRole("button", { name: "Sign in" }).click(); await page.waitForURL(/today/);
await page.goto(base + "/closet");
await page.getByRole("link", { name: /white tee/i }).first().click();
await page.getByTestId("see-on-me").click(); await page.getByTestId("complete-ask").waitFor(); await shot("01-add-a-bottom");
await page.getByTestId("complete-option").first().click(); await page.getByTestId("complete-ask").waitFor(); await shot("02-add-shoes");
await page.getByTestId("complete-option").first().click();
await page.getByTestId("mirror-go-with").waitFor({ timeout: 30000 }); await shot("03-the-picture");
await page.getByTestId("mirror-go-with").scrollIntoViewIfNeeded(); await shot("04-to-go-with-it");
await page.getByTestId("mirror-row-top").getByTestId("mirror-swap").first().click();
await page.getByTestId("mirror-go-with").waitFor({ timeout: 30000 }); await page.getByTestId("mirror-pieces").scrollIntoViewIfNeeded(); await shot("05-swapped-top");
await page.keyboard.press("Escape");
await page.goto(base + "/closet"); await page.getByTestId("closet-mirror").click();
await page.getByTestId("item-card").filter({ hasText: /dark jeans/i }).click(); await page.getByTestId("see-picked").click();
await page.getByTestId("complete-ask").waitFor(); await shot("06-picks-add-a-top");
await browser.close();
console.log("shots done");
