/** Dev-only: sizes by item type (brand sheet + chips), measurement pickers + likely sizes, Add screen store doors, Smooth more. */
import { chromium, devices } from "@playwright/test";
import { execSync } from "node:child_process";
const out = process.argv[2];
const env = { ...process.env, DATABASE_URL: "postgresql://postgres@localhost:5433/fenscloset_e2e", DEV_MODE: "true", SEED_FORCE: "true", MOCK_S3: "true" };
execSync(`psql -h localhost -p 5433 -U postgres -d fenscloset_e2e -c 'DROP SCHEMA public CASCADE; CREATE SCHEMA public;'`, { stdio: "ignore" });
execSync("npx prisma migrate deploy && npx tsx prisma/seed.ts && npx tsx e2e/set-password.ts jeff@everbowl.com closet-rocks-2026", { stdio: "ignore", env });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
const base = "http://localhost:3100";
const ctx = await browser.newContext({ ...devices["iPhone 15"] });
const page = await ctx.newPage();
await page.goto(base + "/login");
await page.getByLabel("Email").fill("jeff@everbowl.com"); await page.getByLabel("Password").fill("closet-rocks-2026");
await page.getByRole("button", { name: "Sign in" }).click(); await page.waitForURL(/today/);
await page.goto(base + "/add"); await page.waitForTimeout(400); await page.screenshot({ path: `${out}/123-add-doors.png`, fullPage: true });
await page.goto(base + "/profile/body");
await page.getByTestId("measure-height").click(); await page.waitForTimeout(400); await page.screenshot({ path: `${out}/124-measure-height-picker.png` });
await page.getByTestId("measure-sheet").getByRole("option", { name: `6'0"` }).click();
await page.getByTestId("measure-weight").click(); await page.getByTestId("measure-sheet").getByRole("option", { name: "185" }).click();
await page.getByTestId("likely-sizes").waitFor(); await page.waitForTimeout(300); await page.screenshot({ path: `${out}/125-body-likely-sizes.png`, fullPage: true });
await page.goto(base + "/profile/brands");
await page.getByTestId("add-my-brand").click(); await page.getByRole("dialog").getByRole("option", { name: "Lululemon" }).click(); await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/126-brand-sheet-by-type.png` });
await page.getByTestId("my-size-tops").click(); await page.waitForTimeout(300); await page.screenshot({ path: `${out}/127-size-chips-tops.png` });
await page.getByTestId("size-sheet").getByRole("option", { name: /^L/ }).click();
await page.getByTestId("my-size-bottoms").click(); await page.waitForTimeout(300); await page.screenshot({ path: `${out}/128-size-chips-bottoms.png` });
await page.getByTestId("size-sheet").getByRole("option", { name: "32", exact: true }).click();
await page.getByTestId("my-brand-url").fill("shop.lululemon.com"); await page.waitForTimeout(200); await page.screenshot({ path: `${out}/129-brand-sheet-filled.png` });
await page.getByTestId("save-my-brand").click(); await page.getByTestId("my-brands").getByText("Lululemon", { exact: true }).waitFor(); await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/130-my-brands-rows.png` });
await browser.close();
