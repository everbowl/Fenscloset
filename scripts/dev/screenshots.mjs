/** Dev-only: seeds the e2e DB, drives the app on :3100, and writes screenshots to the given folder. */
import { chromium, devices } from "@playwright/test";
import { execSync } from "node:child_process";
const out = process.argv[2];
const env = { ...process.env, DATABASE_URL: "postgresql://postgres@localhost:5433/fenscloset_e2e", DEV_MODE: "true" };
execSync(`psql -h localhost -p 5433 -U postgres -d fenscloset_e2e -c 'DROP SCHEMA public CASCADE; CREATE SCHEMA public;'`, { stdio: "ignore" });
execSync("npx prisma migrate deploy && npx tsx prisma/seed.ts && npx tsx e2e/set-password.ts jeff@everbowl.com closet-rocks-2026", { stdio: "ignore", env });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
const ctx = await browser.newContext({ ...devices["iPhone 15"] });
const page = await ctx.newPage();
const base = "http://localhost:3100";
await page.goto(base + "/login");
await page.getByLabel("Email").fill("jeff@everbowl.com"); await page.getByLabel("Password").fill("closet-rocks-2026");
await page.getByRole("button", { name: "Sign in" }).click(); await page.waitForURL(/today/);
await page.goto(base + "/admin/people"); await page.screenshot({ path: `${out}/admin-people.png` });
await page.getByRole("button", { name: "Add person" }).click(); await page.getByRole("dialog").getByLabel("Role").selectOption("minor");
await page.screenshot({ path: `${out}/admin-invite.png` });
await page.goto(base + "/admin/lists"); await page.screenshot({ path: `${out}/admin-lists.png` });
await page.goto(base + "/admin/lists/color"); await page.screenshot({ path: `${out}/admin-colors.png` });
await page.goto(base + "/admin/lists/subcategory"); await page.screenshot({ path: `${out}/admin-subcategories.png` });
await page.goto(base + "/admin/rules"); await page.screenshot({ path: `${out}/admin-rules.png` });
await page.goto(base + "/forgot-password"); await page.screenshot({ path: `${out}/forgot.png` });
const desk = await (await browser.newContext({ ...devices["Desktop Chrome"], storageState: await ctx.storageState() })).newPage();
await desk.goto(base + "/admin/lists/color"); await desk.screenshot({ path: `${out}/admin-colors-desktop.png` });
await browser.close();
console.log("done");
