import { chromium, devices } from "@playwright/test";
import { execSync } from "node:child_process";
const out = process.argv[2];
const env = { ...process.env, DATABASE_URL: "postgresql://postgres@localhost:5433/fenscloset_e2e", DEV_MODE: "true", SEED_FORCE: "true", MOCK_S3: "true" };
execSync(`psql -h localhost -p 5433 -U postgres -d fenscloset_e2e -c 'DROP SCHEMA public CASCADE; CREATE SCHEMA public;'`, { stdio: "ignore" });
execSync("npx prisma migrate deploy && npx tsx prisma/seed.ts && npx tsx e2e/set-password.ts jeff@everbowl.com closet-rocks-2026 && npx tsx e2e/seed-closets.ts Jeff", { stdio: "ignore", env });
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM || undefined });
const ctx = await browser.newContext({ ...devices["iPhone 15"] });
const page = await ctx.newPage();
const base = "http://localhost:3100";
const shot = async (name, full = false) => { await page.waitForTimeout(500); await page.screenshot({ path: `${out}/${name}.png`, fullPage: full }); };
await page.goto(base + "/login");
await page.getByLabel("Email").fill("jeff@everbowl.com"); await page.getByLabel("Password").fill("closet-rocks-2026");
await page.getByRole("button", { name: "Sign in" }).click(); await page.waitForURL(/today/);
await shot("01-today", true);
await page.goto(base + "/closet"); await page.getByTestId("closet-mirror").waitFor(); await shot("02-closet");
await page.getByTestId("closet-mirror").click(); await page.getByTestId("pick-bar").waitFor(); await shot("03-closet-pick");
await page.goto(base + "/closet"); await page.locator("a[href^='/closet/c']").first().click(); await page.waitForURL(/\/closet\/c/); await shot("04-piece", true);
await page.goto(base + "/shop");
await page.getByTestId("paste-link").click();
await page.getByRole("dialog").getByRole("textbox").fill("https://mock.example/p/1");
await page.getByRole("dialog").getByRole("button", { name: "Save" }).click();
await page.getByTestId("shop-result").waitFor({ timeout: 60000 }); await shot("05-shop", true);
await page.goto(base + "/add"); await page.getByTestId("add-doors").waitFor(); await shot("06-add", true);
await page.goto(base + "/profile/brands"); await shot("07-brands", true);
await page.goto(base + "/admin/rules"); await shot("08-rules", true);
await browser.close();
console.log("shots done");
